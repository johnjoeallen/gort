//! HIR to C.
//!
//! Ownership discipline (D18 item 1): every handle owns a count. A value that is copied or passed takes one
//! (`own_value`), and whoever holds a count drops it: locals at scope exit on every path, temporaries at the end of
//! their statement, parameters by the callee at function exit. Slice 0 copies on every pass and moves only out of a
//! temporary; moving the last use of a local is a later optimisation.

use crate::ast::{BinOp, UnOp};
use crate::hir::*;

const RUNTIME: &str = include_str!("gort_rt0.h");

pub fn generate(prog: &Program) -> String {
    let mut out = String::new();
    out.push_str("/* generated by gortc (slice 0) */\n");
    out.push_str(RUNTIME);
    out.push('\n');
    out.push_str(&manifest(prog));
    let g = Gen { prog };
    g.emit_types(&mut out);
    g.emit_prototypes(&mut out);
    g.emit_globals(&mut out);
    g.emit_literals(&mut out);
    g.emit_struct_helpers(&mut out);
    let mut bodies = String::new();
    for fid in 0..prog.fns.len() {
        if prog.fns[fid].body.is_some() {
            bodies.push_str(&FnGen::new(prog, fid).run());
        }
    }
    // element drops for arrays whose elements hold counts, found while generating the bodies
    let edrops = EDROPS.with(|e| std::mem::take(&mut *e.borrow_mut()));
    for (name, el) in &edrops {
        out.push_str(&format!("static void {}(void* p);\n", name));
        let _ = el;
    }
    for (name, el) in &edrops {
        let cty = ctype(prog, el);
        let d = drop_code(prog, el, "(*e)").unwrap_or_default();
        out.push_str(&format!("static void {}(void* p) {{ {}* e = ({}*)p; {} }}\n", name, cty, cty, d));
    }
    let thunks = THUNKS.with(|t| std::mem::take(&mut *t.borrow_mut()));
    for fid in &thunks {
        let f = &prog.fns[*fid];
        let ps: Vec<String> = f.param_tys.iter().enumerate().map(|(i, t)| format!("{} a{}", ctype(prog, t), i)).collect();
        let names: Vec<String> = (0..ps.len()).map(|i| format!("a{}", i)).collect();
        let mut sig = ps.clone();
        let body = if f.ret == Ty::Unit {
            format!("{}({}); return 0;", f.cname, names.join(", "))
        } else {
            sig.push(format!("{}* r", ctype(prog, &f.ret)));
            format!("*r = {}({}); return 0;", f.cname, names.join(", "))
        };
        out.push_str(&format!("static int {}_thunk({}) {{ {} }}\n", f.cname, if sig.is_empty() { "void".into() } else { sig.join(", ") }, body));
    }
    for d in EXTDEFS.with(|e| std::mem::take(&mut *e.borrow_mut())) {
        out.push_str(&d);
    }
    out.push_str(&eq_defs(prog));
    out.push_str(&json_decoders(prog));
    out.push_str(&bodies);
    if let Some(m) = prog.main {
        let inits: String = prog.global_inits.iter().map(|f| format!("    {}();\n", prog.fns[*f].cname)).collect();
        let drops: String = prog
            .globals
            .iter()
            .rev()
            .filter(|g| !g.is_extern)
            .filter_map(|g| drop_code(prog, &g.ty, &format!("gort_g_{}", g.name)))
            .map(|d| format!("    {}\n", d))
            .collect();
        out.push_str(&format!(
            "\nint main(void) {{\n{}    {}();\n{}    if (gort_live != 0) {{\n        fprintf(stderr, \"gort: %zu object(s) still live at exit (leak)\\n\", gort_live);\n        return 70;\n    }}\n    return 0;\n}}\n",
            inits,
            prog.fns[m].cname,
            drops
        ));
    }
    out
}

/// Every generic instance the program uses, once. The `extern` ones are what the C runtime must provide:
/// it defines `GORT_EXTERN_INSTANCE(template, struct)` and expands this list to generate their functions.
pub fn manifest(prog: &Program) -> String {
    let mut s = String::from("/* generic instances (whole program, each once) */\n#define GORT_EXTERN_INSTANCES(X)");
    for i in prog.instances.iter().filter(|i| i.is_extern) {
        s.push_str(&format!(" \\\n    X({}, G_{})", i.template, prog.structs[i.sid].name));
    }
    s.push('\n');
    for i in &prog.instances {
        s.push_str(&format!("/* instance {} = G_{}{} */\n", i.shown, prog.structs[i.sid].name, if i.is_extern { " (extern)" } else { "" }));
    }
    s
}

thread_local! {
    static EXTDEFS: std::cell::RefCell<Vec<String>> = const { std::cell::RefCell::new(Vec::new()) };
    static EQS: std::cell::RefCell<std::collections::BTreeSet<usize>> = const { std::cell::RefCell::new(std::collections::BTreeSet::new()) };
    static JSONS: std::cell::RefCell<std::collections::BTreeSet<usize>> = const { std::cell::RefCell::new(std::collections::BTreeSet::new()) };
    static THUNKS: std::cell::RefCell<std::collections::BTreeSet<usize>> = const { std::cell::RefCell::new(std::collections::BTreeSet::new()) };
    static EDROPS: std::cell::RefCell<std::collections::BTreeMap<String, Ty>> = const { std::cell::RefCell::new(std::collections::BTreeMap::new()) };
}

struct Gen<'a> {
    prog: &'a Program,
}

fn field_c(name: &str) -> String {
    format!("f_{}", name)
}

impl<'a> Gen<'a> {
    fn ctype(&self, t: &Ty) -> String {
        ctype(self.prog, t)
    }

    fn emit_types(&self, out: &mut String) {
        for s in &self.prog.structs {
            out.push_str(&format!("typedef struct G_{0} G_{0};\n", s.name));
        }
        let n = self.prog.structs.len();
        let mut done = vec![false; n];
        let mut opts: std::collections::HashSet<String> = std::collections::HashSet::new();
        fn visit(g: &Gen, i: usize, done: &mut Vec<bool>, opts: &mut std::collections::HashSet<String>, out: &mut String) {
            if done[i] {
                return;
            }
            done[i] = true;
            for f in &g.prog.structs[i].fields {
                if let Some(j) = f.ty.inline_struct() {
                    visit(g, j, done, opts, out);
                }
                g.emit_opt(&f.ty, opts, out);
            }
            let s = &g.prog.structs[i];
            out.push_str(&format!("struct G_{} {{\n", s.name));
            if s.fields.is_empty() {
                out.push_str("    char _empty;\n");
            }
            for f in &s.fields {
                out.push_str(&format!("    {} {};\n", g.ctype(&f.ty), field_c(&f.name)));
            }
            out.push_str("};\n");
        }
        for i in 0..n {
            visit(self, i, &mut done, &mut opts, out);
        }
        for f in &self.prog.fns {
            self.emit_opt(&f.ret, &mut opts, out);
            for t in f.param_tys.iter().chain(f.vars.iter().map(|v| &v.ty)) {
                self.emit_opt(t, &mut opts, out);
            }
        }
    }

    /// The presence-flag wrapper for an optional scalar or value, once.
    fn emit_opt(&self, t: &Ty, done: &mut std::collections::HashSet<String>, out: &mut String) {
        if let Ty::Opt(i) = t {
            if !i.is_handle() {
                let n = opt_name(self.prog, i);
                if done.insert(n.clone()) {
                    out.push_str(&format!("typedef struct {{ bool has; {} v; }} {};\n", ctype(self.prog, i), n));
                }
            }
        }
    }

    fn proto(&self, fid: FnId) -> String {
        let f = &self.prog.fns[fid];
        let mut ps: Vec<String> = Vec::new();
        if let (Some(o), false) = (f.owner, f.is_static) {
            ps.push(format!("G_{}* self", self.prog.structs[o].name));
        }
        for (i, t) in f.param_tys.iter().enumerate() {
            if f.is_extern && matches!(t, Ty::Fn(..)) {
                // a function given to the runtime travels as (code, environment); the code takes the environment first
                ps.push(format!("void* p{}, void* p{}_env", i, i));
            } else {
                ps.push(format!("{} p{}", self.ctype(t), i));
            }
        }
        let rt = if f.throws.is_empty() {
            self.ctype(&f.ret)
        } else {
            if f.ret != Ty::Unit {
                ps.push(format!("{}* ret_out", self.ctype(&f.ret)));
            }
            "int".to_string()
        };
        let ps = if ps.is_empty() { "void".to_string() } else { ps.join(", ") };
        format!("{} {} {}({})", if f.is_extern { "extern" } else { "static" }, rt, f.cname, ps)
    }

    fn emit_prototypes(&self, out: &mut String) {
        for s in &self.prog.structs {
            out.push_str(&format!("static void G_{0}_release(G_{0}* p);\n", s.name));
            if s.needs_drop {
                out.push_str(&format!("static void G_{0}_drop(G_{0}* s);\n", s.name));
                out.push_str(&format!("static void G_{0}_copy(G_{0}* d, const G_{0}* s);\n", s.name));
            }
        }
        for fid in 0..self.prog.fns.len() {
            out.push_str(&format!("{};\n", self.proto(fid)));
        }
    }

    fn emit_globals(&self, out: &mut String) {
        for g in &self.prog.globals {
            let kw = if g.is_extern { "extern" } else { "static" };
            out.push_str(&format!("{} {} gort_g_{};\n", kw, self.ctype(&g.ty), g.name));
        }
    }

    fn emit_literals(&self, out: &mut String) {
        for (i, s) in self.prog.strings.iter().enumerate() {
            let mut lit = String::new();
            for b in s {
                lit.push_str(&format!("\\{:03o}", b));
            }
            out.push_str(&format!("static gort_str gort_lit_{} = {{ 1, {}, (const uint8_t*)\"{}\", true }};\n", i, s.len(), lit));
        }
    }

    fn field_copy_line(&self, ty: &Ty, fc: &str) -> String {
        match ty {
            Ty::Ref(t) => format!("d->{0} = (G_{1}*)gort_retain(s->{0});", fc, self.prog.structs[*t].name),
            Ty::Str => format!("d->{0} = gort_str_retain(s->{0});", fc),
            Ty::Arr(_) => format!("d->{0} = gort_arr_retain(s->{0});", fc),
            Ty::Struct(t) if self.prog.structs[*t].needs_drop => {
                format!("G_{}_copy(&d->{}, &s->{});", self.prog.structs[*t].name, fc, fc)
            }
            Ty::Opt(i) if i.is_handle() => match &**i {
                Ty::Ref(t) => format!("d->{0} = s->{0} ? (G_{1}*)gort_retain(s->{0}) : NULL;", fc, self.prog.structs[*t].name),
                Ty::Str => format!("d->{0} = s->{0} ? gort_str_retain(s->{0}) : NULL;", fc),
                _ => format!("d->{0} = s->{0} ? gort_arr_retain(s->{0}) : NULL;", fc),
            },
            Ty::Opt(i) if matches!(&**i, Ty::Struct(t) if self.prog.structs[*t].needs_drop) => {
                let Ty::Struct(t) = &**i else { unreachable!() };
                format!("d->{0} = s->{0}; if (s->{0}.has) G_{1}_copy(&d->{0}.v, &s->{0}.v);", fc, self.prog.structs[*t].name)
            }
            _ => format!("d->{0} = s->{0};", fc),
        }
    }

    fn emit_struct_helpers(&self, out: &mut String) {
        for s in &self.prog.structs {
            let n = &s.name;
            if s.needs_drop && !s.variants.is_empty() {
                // an enum: only the fields of the variant the tag names hold anything
                out.push_str(&format!("static void G_{}_drop(G_{}* s) {{\n    switch (s->f__tag) {{\n", n, n));
                for (vi, v) in s.variants.iter().enumerate() {
                    let ds: Vec<String> = v.fields.iter().rev().filter_map(|&i| drop_code(self.prog, &s.fields[i].ty, &format!("s->{}", field_c(&s.fields[i].name)))).collect();
                    if !ds.is_empty() {
                        out.push_str(&format!("    case {}: {} break;\n", vi, ds.join(" ")));
                    }
                }
                out.push_str("    default: break;\n    }\n}\n");
                out.push_str(&format!("static void G_{0}_copy(G_{0}* d, const G_{0}* s) {{\n    *d = *s;\n    switch (s->f__tag) {{\n", n));
                for (vi, v) in s.variants.iter().enumerate() {
                    let cs: Vec<String> = v.fields.iter().filter(|&&i| drop_code(self.prog, &s.fields[i].ty, "x").is_some()).map(|&i| self.field_copy_line(&s.fields[i].ty, &field_c(&s.fields[i].name))).collect();
                    if !cs.is_empty() {
                        out.push_str(&format!("    case {}: {} break;\n", vi, cs.join(" ")));
                    }
                }
                out.push_str("    default: break;\n    }\n}\n");
            } else if s.needs_drop {
                out.push_str(&format!("static void G_{}_drop(G_{}* s) {{\n", n, n));
                if let Some(c) = s.cleanup {
                    out.push_str(&format!("    {}(s);\n", self.prog.fns[c].cname));
                }
                for f in s.fields.iter().rev() {
                    if let Some(d) = drop_code(self.prog, &f.ty, &format!("s->{}", field_c(&f.name))) {
                        out.push_str(&format!("    {}\n", d));
                    }
                }
                out.push_str("}\n");
                out.push_str(&format!("static void G_{}_copy(G_{}* d, const G_{}* s) {{\n", n, n, n));
                for f in &s.fields {
                    out.push_str(&format!("    {}\n", self.field_copy_line(&f.ty, &field_c(&f.name))));
                }
                out.push_str("}\n");
            }
            out.push_str(&format!("static void G_{}_release(G_{}* p) {{\n", n, n));
            out.push_str("    if (gort_release_last(p)) {\n");
            if s.needs_drop {
                out.push_str(&format!("        G_{}_drop(p);\n", n));
            }
            out.push_str("        gort_free(p);\n    }\n}\n");
        }
    }
}

fn ctype(prog: &Program, t: &Ty) -> String {
    match t {
        Ty::Unit => "void".into(),
        Ty::Bool => "bool".into(),
        Ty::Int(i) => i.c_name().into(),
        Ty::F64 => "double".into(),
        Ty::Str => "gort_str*".into(),
        Ty::Struct(s) => format!("G_{}", prog.structs[*s].name),
        Ty::Ref(s) => format!("G_{}*", prog.structs[*s].name),
        Ty::Arr(_) => "gort_arr*".into(),
        Ty::Obj(s) => format!("G_{}", prog.structs[*s].name),
        Ty::Opt(i) if i.is_handle() => ctype(prog, i),
        Ty::Opt(i) => opt_name(prog, i),
        Ty::Null => "void*".into(),
        Ty::Dur | Ty::Inst => "int64_t".into(),
        Ty::Exc => "gort_exc_t".into(),
        Ty::Fn(..) => "void*".into(),
        Ty::Error => "int".into(),
    }
}

/// The statement that releases the counts held by `lv` (an lvalue of type `t`), if it holds any.
fn drop_code(prog: &Program, t: &Ty, lv: &str) -> Option<String> {
    match t {
        Ty::Ref(s) => Some(format!("G_{}_release({});", prog.structs[*s].name, lv)),
        Ty::Str => Some(format!("gort_str_release({});", lv)),
        Ty::Arr(_) => Some(format!("gort_arr_release({});", lv)),
        Ty::Exc => Some(format!("gort_exc_release(&{});", lv)),
        Ty::Opt(i) if i.is_handle() => drop_code(prog, i, lv).map(|d| format!("if ({}) {{ {} }}", lv, d)),
        Ty::Opt(i) => drop_code(prog, i, &format!("{}.v", lv)).map(|d| format!("if ({}.has) {{ {} }}", lv, d)),
        Ty::Struct(s) if prog.structs[*s].needs_drop => Some(format!("G_{}_drop(&{});", prog.structs[*s].name, lv)),
        _ => None,
    }
}

#[derive(Clone)]
struct Val {
    c: String,
    /// the name of an owned temporary that holds this value (registered for dropping)
    own: Option<String>,
}

impl Val {
    fn plain(c: impl Into<String>) -> Val {
        Val { c: c.into(), own: None }
    }
}

struct Temp {
    name: String,
    drop: String,
}

struct FnGen<'a> {
    prog: &'a Program,
    f: &'a FnInfo,
    out: Vec<String>,
    ind: usize,
    tmpn: usize,
    /// per scope: drop statements in declaration order
    scopes: Vec<Vec<String>>,
    frames: Vec<Vec<Temp>>,
    loop_scope: Vec<usize>,
    loop_ids: Vec<Option<usize>>,
    pending_label: bool,
    var_c: Vec<String>,
    dead: bool,
    try_stack: Vec<TryCtx>,
    labels: usize,
}

struct TryCtx {
    label: String,
    scope_depth: usize,
    frame_depth: usize,
    catches_null: bool,
}

fn sanitize(s: &str) -> String {
    s.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect()
}

fn has_effects(e: &TExpr) -> bool {
    match &e.kind {
        EK::Borrow(..) | EK::BoxVal(..) | EK::Call(..) | EK::CallInd(..) | EK::RtCall(..) | EK::Json(..) | EK::ExternFn(..) | EK::Lambda(..) | EK::Method(..) | EK::Builtin(..) | EK::NewObj(..) | EK::NewArr(..) => true,
        EK::Field(b, _) | EK::Deref(b) | EK::Len(b) | EK::Unary(_, b) | EK::Cast(b) => has_effects(b),
        EK::Slice(..) | EK::Cond(..) | EK::ArrLit(..) => true,
        EK::Index(a, b) | EK::Binary(_, a, b) => has_effects(a) || has_effects(b),
        EK::StructLit(_, fs) => fs.iter().any(|(_, x)| has_effects(x)),
        _ => false,
    }
}

impl<'a> FnGen<'a> {
    fn new(prog: &'a Program, fid: FnId) -> FnGen<'a> {
        let f = &prog.fns[fid];
        let var_c = f.vars.iter().enumerate().map(|(i, v)| format!("v_{}_{}", sanitize(&v.name), i)).collect();
        FnGen { prog, f, out: Vec::new(), ind: 1, tmpn: 0, scopes: Vec::new(), frames: Vec::new(), loop_scope: Vec::new(), loop_ids: Vec::new(), pending_label: false, var_c, dead: false, try_stack: Vec::new(), labels: 0 }
    }

    fn ct(&self, t: &Ty) -> String {
        ctype(self.prog, t)
    }
    fn line(&mut self, s: impl AsRef<str>) {
        let pad = "    ".repeat(self.ind);
        self.out.push(format!("{}{}", pad, s.as_ref()));
    }
    fn tmp(&mut self) -> String {
        self.tmpn += 1;
        format!("t{}", self.tmpn)
    }

    fn run(mut self) -> String {
        let f = self.f;
        // header
        let mut ps: Vec<String> = Vec::new();
        if let (Some(o), false) = (f.owner, f.is_static) {
            ps.push(format!("G_{}* self", self.prog.structs[o].name));
        }
        for (i, t) in f.param_tys.iter().enumerate() {
            ps.push(format!("{} p{}", self.ct(t), i));
        }
        let throws = !f.throws.is_empty();
        let rt = if throws {
            if f.ret != Ty::Unit {
                ps.push(format!("{}* ret_out", self.ct(&f.ret)));
            }
            "int".to_string()
        } else {
            self.ct(&f.ret)
        };
        let ps = if ps.is_empty() { "void".to_string() } else { ps.join(", ") };
        let head = format!("\nstatic {} {}({}) {{", rt, f.cname, ps);
        // parameters become locals the function owns and drops
        self.scopes.push(Vec::new());
        for (i, vid) in f.params.clone().iter().enumerate() {
            let name = self.var_c[*vid].clone();
            let ty = f.param_tys[i].clone();
            let cty = self.ct(&ty);
            self.line(format!("{} {} = p{};", cty, name, i));
            // a borrowed parameter is the caller's: nothing to release here
            if f.borrowed.get(i).copied().unwrap_or(false) {
                continue;
            }
            if let Some(d) = drop_code(self.prog, &ty, &name) {
                self.scopes.last_mut().unwrap().push(d);
            }
        }
        let body = f.body.as_ref().unwrap();
        for s in &body.stmts {
            self.stmt(s);
        }
        if !self.dead {
            self.emit_scope_drops_to(0);
            if throws {
                self.line("return 0;");
            }
        }
        let mut s = head;
        s.push('\n');
        for l in &self.out {
            s.push_str(l);
            s.push('\n');
        }
        s.push_str("}\n");
        s
    }

    // ---------------- scopes and temporaries ----------------

    fn emit_scope_drops_to(&mut self, depth: usize) {
        // drops of scopes[depth..], innermost first, each in reverse declaration order
        let mut lines = Vec::new();
        for sc in self.scopes[depth..].iter().rev() {
            for d in sc.iter().rev() {
                lines.push(d.clone());
            }
        }
        for l in lines {
            self.line(l);
        }
    }

    fn push_frame(&mut self) {
        self.frames.push(Vec::new());
    }
    fn pop_frame(&mut self) {
        let fr = self.frames.pop().unwrap();
        for t in fr.iter().rev() {
            let d = t.drop.clone();
            self.line(d);
        }
    }
    fn register_temp(&mut self, name: &str, drop: String) {
        self.frames.last_mut().unwrap().push(Temp { name: name.to_string(), drop });
    }
    fn unregister(&mut self, name: &str) {
        for fr in self.frames.iter_mut().rev() {
            if let Some(p) = fr.iter().position(|t| t.name == name) {
                fr.remove(p);
                return;
            }
        }
    }

    /// Produces a C expression holding an owned copy of `v` (or `v` itself if it is an owned temporary: a move).
    fn own_value(&mut self, v: Val, ty: &Ty) -> String {
        if let Some(n) = v.own {
            self.unregister(&n);
            return n;
        }
        self.copy_value(v, ty)
    }

    /// Like `own_value` but never moves out of a temporary: the temporary stays registered and dies at the end of
    /// its statement. Arguments use this, so a cleanup() runs when the statement ends, not when a callee returns.
    fn copy_value(&mut self, v: Val, ty: &Ty) -> String {
        let v = Val { c: v.c, own: None };
        let simple = v.c.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false)
            || v.c == "true"
            || v.c == "false"
            || (v.c.starts_with('t') && v.c.len() > 1 && v.c[1..].chars().all(|c| c.is_ascii_digit()));
        match ty {
            Ty::Ref(s) => {
                let t = self.tmp();
                let cn = self.prog.structs[*s].name.clone();
                self.line(format!("G_{0}* {1} = (G_{0}*)gort_retain({2});", cn, t, v.c));
                t
            }
            Ty::Str => {
                let t = self.tmp();
                self.line(format!("gort_str* {} = gort_str_retain({});", t, v.c));
                t
            }
            Ty::Arr(_) => {
                let t = self.tmp();
                self.line(format!("gort_arr* {} = gort_arr_retain({});", t, v.c));
                t
            }
            Ty::Struct(s) if self.prog.structs[*s].needs_drop => {
                let t = self.tmp();
                let cn = self.prog.structs[*s].name.clone();
                if v.c.chars().all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '_' | '.' | '>' | '-')) {
                    self.line(format!("G_{0} {1}; G_{0}_copy(&{1}, &{2});", cn, t, v.c));
                } else {
                    // not an lvalue (an unwrapped optional, a call result): look at it through a shallow temporary
                    let src = self.tmp();
                    self.line(format!("G_{0} {3} = {2}; G_{0} {1}; G_{0}_copy(&{1}, &{3});", cn, t, v.c, src));
                }
                t
            }
            Ty::Opt(i) if i.is_handle() => {
                let t = self.tmp();
                let cty = self.ct(ty);
                let r = match &**i {
                    Ty::Ref(s) => format!("(G_{}*)gort_retain({})", self.prog.structs[*s].name, v.c),
                    Ty::Str => format!("gort_str_retain({})", v.c),
                    _ => format!("gort_arr_retain({})", v.c),
                };
                self.line(format!("{0} {1} = {2}; if ({1}) {1} = {3};", cty, t, v.c, r));
                t
            }
            Ty::Opt(i) if matches!(&**i, Ty::Struct(s) if self.prog.structs[*s].needs_drop) => {
                let Ty::Struct(s) = &**i else { unreachable!() };
                let t = self.tmp();
                let cty = self.ct(ty);
                let cn = self.prog.structs[*s].name.clone();
                self.line(format!("{0} {1} = {2}; if ({1}.has) G_{3}_copy(&{1}.v, &({2}).v);", cty, t, v.c, cn));
                t
            }
            _ => {
                if simple {
                    v.c
                } else {
                    let t = self.tmp();
                    let cty = self.ct(ty);
                    self.line(format!("{} {} = {};", cty, t, v.c));
                    t
                }
            }
        }
    }

    // ---------------- statements ----------------

    fn block(&mut self, b: &TBlock) {
        let saved = self.dead;
        self.dead = false;
        self.line("{");
        self.ind += 1;
        self.scopes.push(Vec::new());
        for s in &b.stmts {
            self.stmt(s);
        }
        if !self.dead {
            let sc = self.scopes.len() - 1;
            self.emit_scope_drops_to(sc);
        }
        self.scopes.pop();
        self.ind -= 1;
        self.line("}");
        self.dead = saved;
    }

    fn declare(&mut self, id: VarId, ty: &Ty) -> String {
        let name = self.var_c[id].clone();
        let cty = self.ct(ty);
        self.line(format!("{} {};", cty, name));
        name
    }

    fn zero_c(&self, ty: &Ty) -> String {
        match ty {
            Ty::Struct(_) | Ty::Opt(_) if !ty.is_handle_opt() => format!("({}){{0}}", self.ct(ty)),
            _ => "0".into(),
        }
    }

    fn eval_fields(&mut self, fields: &[(usize, TExpr)]) -> Vec<(usize, String)> {
        let mut out = Vec::new();
        for (idx, e) in fields {
            if matches!(e.kind, EK::Zero) {
                out.push((*idx, self.zero_c(&e.ty)));
                continue;
            }
            let v = self.expr(e);
            let s = self.own_value(v, &e.ty);
            // owned but not yet stored: a later field that throws must still release it
            if let Some(d) = drop_code(self.prog, &e.ty, &s) {
                self.register_temp(&s, d);
            }
            out.push((*idx, s));
        }
        out
    }

    /// Every error exit: drop the pending temporaries and locals down to the nearest `try`, then jump or return.
    fn throw_exit(&mut self) {
        let (fd, sd, label) = match self.try_stack.last() {
            Some(t) => (t.frame_depth, t.scope_depth, Some(t.label.clone())),
            None => (0, 0, None),
        };
        let mut drops = Vec::new();
        for fr in self.frames[fd..].iter().rev() {
            for t in fr.iter().rev() {
                drops.push(t.drop.clone());
            }
        }
        for d in drops {
            self.line(d);
        }
        self.emit_scope_drops_to(sd);
        match label {
            Some(l) => self.line(format!("goto {};", l)),
            None => self.line("return 1;"),
        }
    }

    fn take_label(&mut self) -> Option<usize> {
        if std::mem::take(&mut self.pending_label) {
            self.labels += 1;
            Some(self.labels)
        } else {
            None
        }
    }

    fn stmt(&mut self, s: &TStmt) {
        match &s.kind {
            TS::Let(id, init) => {
                let ty = self.f.vars[*id].ty.clone();
                let name = self.declare(*id, &ty);
                self.line("{");
                self.ind += 1;
                self.push_frame();
                let v = self.expr(init);
                let o = self.own_value(v, &init.ty);
                self.line(format!("{} = {};", name, o));
                self.pop_frame();
                self.ind -= 1;
                self.line("}");
                if let Some(d) = drop_code(self.prog, &ty, &name) {
                    self.scopes.last_mut().unwrap().push(d);
                }
            }
            TS::LetObj(id, sid, fields) => {
                let counted = self.f.vars[*id].converted;
                let sn = self.prog.structs[*sid].name.clone();
                let name = self.var_c[*id].clone();
                if counted {
                    self.line(format!("G_{}* {};", sn, name));
                } else {
                    self.line(format!("G_{} {};", sn, name));
                }
                self.line("{");
                self.ind += 1;
                self.push_frame();
                let fs = self.eval_fields(fields);
                let (acc, _) = if counted {
                    self.line(format!("{0} = (G_{1}*)gort_new(sizeof(G_{1}));", name, sn));
                    (format!("{}->", name), 0)
                } else {
                    (format!("{}.", name), 0)
                };
                if self.prog.structs[*sid].fields.is_empty() && !counted {
                    self.line(format!("{}._empty = 0;", name));
                }
                for (idx, o) in fs {
                    let fname = field_c(&self.prog.structs[*sid].fields[idx].name);
                    self.line(format!("{}{} = {};", acc, fname, o));
                    self.unregister(&o);
                }
                self.pop_frame();
                self.ind -= 1;
                self.line("}");
                let d = if counted { format!("G_{}_release({});", sn, name) } else { format!("G_{}_drop(&{});", sn, name) };
                if counted || self.prog.structs[*sid].needs_drop {
                    self.scopes.last_mut().unwrap().push(d);
                }
            }
            TS::Assign(place, val) => {
                self.line("{");
                self.ind += 1;
                self.push_frame();
                let p = self.expr(place);
                let v = self.expr(val);
                let o = self.own_value(v, &val.ty);
                match drop_code(self.prog, &place.ty, "old") {
                    Some(d) => {
                        let cty = self.ct(&place.ty);
                        self.line(format!("{} old = {};", cty, p.c));
                        self.line(format!("{} = {};", p.c, o));
                        self.line(d);
                    }
                    None => self.line(format!("{} = {};", p.c, o)),
                }
                self.pop_frame();
                self.ind -= 1;
                self.line("}");
            }
            TS::AssignOp(op, place, val) => {
                self.line("{");
                self.ind += 1;
                self.push_frame();
                let p = self.expr(place);
                let v = self.expr(val);
                let o = self.own_value(v, &val.ty);
                if matches!(op, BinOp::Div | BinOp::Rem) && matches!(place.ty, Ty::Int(_)) {
                    self.line(format!("GORT_NZ({});", o));
                }
                self.line(format!("{} {}= {};", p.c, binop_c(*op), o));
                self.pop_frame();
                self.ind -= 1;
                self.line("}");
            }
            TS::Expr(e) => {
                self.line("{");
                self.ind += 1;
                self.push_frame();
                self.expr(e);
                self.pop_frame();
                self.ind -= 1;
                self.line("}");
            }
            TS::If(c, t, e) => {
                let cn = self.tmp();
                self.line(format!("bool {};", cn));
                self.line("{");
                self.ind += 1;
                self.push_frame();
                let v = self.expr(c);
                self.line(format!("{} = {};", cn, v.c));
                self.pop_frame();
                self.ind -= 1;
                self.line("}");
                self.line(format!("if ({})", cn));
                let saved = self.dead;
                self.block(t);
                if let Some(e) = e {
                    self.line("else");
                    self.block(e);
                }
                self.dead = saved;
            }
            TS::While(c, body) => {
                let lid = self.take_label();
                self.line("for (;;) {");
                self.ind += 1;
                let cn = self.tmp();
                self.line(format!("bool {};", cn));
                self.line("{");
                self.ind += 1;
                self.push_frame();
                let v = self.expr(c);
                self.line(format!("{} = {};", cn, v.c));
                self.pop_frame();
                self.ind -= 1;
                self.line("}");
                self.line(format!("if (!{}) break;", cn));
                self.loop_scope.push(self.scopes.len());
                self.loop_ids.push(lid);
                let saved = self.dead;
                self.block(body);
                self.dead = saved;
                self.loop_scope.pop();
                self.loop_ids.pop();
                if let Some(id) = lid {
                    self.line(format!("cont_{}: __attribute__((unused));", id));
                }
                self.ind -= 1;
                self.line("}");
                if let Some(id) = lid {
                    self.line(format!("brk_{}: __attribute__((unused));", id));
                }
            }
            TS::Loop(body) => {
                let lid = self.take_label();
                self.line("for (;;) {");
                self.loop_scope.push(self.scopes.len());
                self.loop_ids.push(lid);
                let saved = self.dead;
                self.block(body);
                self.dead = saved;
                self.loop_scope.pop();
                self.loop_ids.pop();
                if let Some(id) = lid {
                    self.line(format!("cont_{}: __attribute__((unused));", id));
                }
                self.line("}");
                if let Some(id) = lid {
                    self.line(format!("brk_{}: __attribute__((unused));", id));
                }
            }
            TS::Labeled(inner) => {
                self.pending_label = true;
                self.stmt(inner);
                self.pending_label = false;
            }
            TS::BreakL(level, cont) => {
                let depth = self.loop_scope[*level];
                let id = self.loop_ids[*level].expect("labeled loop");
                self.emit_scope_drops_to(depth);
                self.line(format!("goto {}_{};", if *cont { "cont" } else { "brk" }, id));
                self.dead = true;
            }
            TS::Break | TS::Continue => {
                let depth = *self.loop_scope.last().unwrap();
                self.emit_scope_drops_to(depth);
                self.line(if matches!(s.kind, TS::Break) { "break;" } else { "continue;" });
                self.dead = true;
            }
            TS::Return(v) => {
                self.line("{");
                self.ind += 1;
                self.push_frame();
                let ret = match v {
                    Some(e) => {
                        let val = self.expr(e);
                        let o = self.own_value(val, &e.ty);
                        let cty = self.ct(&e.ty);
                        self.line(format!("{} ret = {};", cty, o));
                        true
                    }
                    None => false,
                };
                // temporaries still pending, in every open frame, then every local of the function
                let mut drops = Vec::new();
                for fr in self.frames.iter().rev() {
                    for t in fr.iter().rev() {
                        drops.push(t.drop.clone());
                    }
                }
                for d in drops {
                    self.line(d);
                }
                self.emit_scope_drops_to(0);
                if !self.f.throws.is_empty() {
                    if ret {
                        self.line("*ret_out = ret;");
                    }
                    self.line("return 0;");
                } else {
                    self.line(if ret { "return ret;" } else { "return;" });
                }
                self.frames.pop();
                self.ind -= 1;
                self.line("}");
                self.dead = true;
            }
            TS::Block(b) => self.block(b),
            TS::SetGlobal(g, init) => {
                self.line("{");
                self.ind += 1;
                self.push_frame();
                let v = self.expr(init);
                let o = self.own_value(v, &init.ty);
                self.line(format!("gort_g_{} = {};", self.prog.globals[*g].name, o));
                self.pop_frame();
                self.ind -= 1;
                self.line("}");
            }
            TS::Throw(sid, fields) => {
                self.line("{");
                self.ind += 1;
                self.push_frame();
                let fs = self.eval_fields(fields);
                let sn = self.prog.structs[*sid].name.clone();
                let t = self.tmp();
                self.line(format!("G_{0}* {1} = (G_{0}*)gort_new(sizeof(G_{0}));", sn, t));
                for (idx, o) in fs {
                    let fname = field_c(&self.prog.structs[*sid].fields[idx].name);
                    self.line(format!("{}->{} = {};", t, fname, o));
                    self.unregister(&o);
                }
                self.line(format!(
                    "gort_exc.obj = {}; gort_exc.id = {}; gort_exc.name = \"{}\"; gort_exc.rel = (void (*)(void*))G_{}_release;",
                    t,
                    sid + 1,
                    sn,
                    sn
                ));
                self.throw_exit();
                self.frames.pop();
                self.ind -= 1;
                self.line("}");
                self.dead = true;
            }
            TS::Try(body, catches) => {
                self.labels += 1;
                let (label, done) = (format!("catch_{}", self.labels), format!("done_{}", self.labels));
                let saved = self.dead;
                self.line("{");
                self.ind += 1;
                let null_exc = self.prog.null_exc;
                let catches_null = catches.iter().any(|c| c.exc == ANY_EXC || Some(c.exc) == null_exc);
                self.try_stack.push(TryCtx { label: label.clone(), scope_depth: self.scopes.len(), frame_depth: self.frames.len(), catches_null });
                self.block(body);
                self.try_stack.pop();
                self.line(format!("goto {};", done));
                self.line(format!("{}: ;", label));
                let mut first = true;
                let mut has_all = false;
                for c in catches {
                    let cond = if c.exc == ANY_EXC {
                        has_all = true;
                        "1".to_string()
                    } else {
                        format!("gort_exc.id == {}", c.exc + 1)
                    };
                    self.line(format!("{}if ({}) {{", if first { "" } else { "else " }, cond));
                    first = false;
                    self.ind += 1;
                    let vty = self.f.vars[c.var].ty.clone();
                    let name = self.declare(c.var, &vty);
                    match &vty {
                        Ty::Ref(s) => self.line(format!("{} = (G_{}*)gort_exc.obj; gort_exc.obj = NULL;", name, self.prog.structs[*s].name)),
                        _ => self.line(format!("{} = gort_exc; gort_exc.obj = NULL;", name)),
                    }
                    self.scopes.push(Vec::new());
                    if let Some(d) = drop_code(self.prog, &vty, &name) {
                        self.scopes.last_mut().unwrap().push(d);
                    }
                    self.dead = false;
                    self.block(&c.body);
                    if !self.dead {
                        let sc = self.scopes.len() - 1;
                        self.emit_scope_drops_to(sc);
                    }
                    self.scopes.pop();
                    self.ind -= 1;
                    self.line("}");
                }
                if !has_all {
                    self.line("else {");
                    self.ind += 1;
                    if self.try_stack.is_empty() && self.f.throws.is_empty() {
                        // sema has shown that nothing else can arrive here
                        self.line("gort_trap(\"unhandled exception\");");
                    } else {
                        self.throw_exit();
                    }
                    self.ind -= 1;
                    self.line("}");
                }
                self.line(format!("{}: ;", done));
                self.ind -= 1;
                self.line("}");
                self.dead = saved;
            }
        }
    }

    // ---------------- expressions ----------------

    fn int_lit(&self, v: i128, it: IntTy) -> String {
        let cty = it.c_name();
        if v < 0 {
            format!("(({})({}LL))", cty, v)
        } else if v > i64::MAX as i128 {
            format!("(({}){}ULL)", cty, v)
        } else {
            format!("(({}){}LL)", cty, v)
        }
    }

    fn expr(&mut self, e: &TExpr) -> Val {
        match &e.kind {
            EK::Int(v) => match &e.ty {
                Ty::Int(it) => Val::plain(self.int_lit(*v, *it)),
                _ => Val::plain(format!("{}", v)),
            },
            EK::Float(v) => {
                let s = format!("{:?}", v);
                Val::plain(if s.contains('.') || s.contains('e') || s.contains("inf") || s.contains("NaN") { s } else { format!("{}.0", s) })
            }
            EK::Bool(b) => Val::plain(if *b { "true" } else { "false" }),
            EK::StrLit(i) => Val::plain(format!("(&gort_lit_{})", i)),
            EK::Var(id) => Val::plain(self.var_c[*id].clone()),
            EK::Global(g) => Val::plain(format!("gort_g_{}", self.prog.globals[*g].name)),
            EK::SelfPlace => Val::plain("(*self)"),
            EK::Field(b, idx) => {
                let bv = self.expr(b);
                let sid = match b.ty {
                    Ty::Struct(s) => s,
                    _ => unreachable!("field of a non-struct"),
                };
                let fname = field_c(&self.prog.structs[sid].fields[*idx].name);
                Val::plain(format!("({}).{}", bv.c, fname))
            }
            EK::Deref(r) => {
                let rv = self.expr(r);
                Val::plain(format!("(*{})", rv.c))
            }
            EK::ObjRef(id) => Val::plain(self.var_c[*id].clone()),
            EK::ObjPlace(id) => {
                if self.f.vars[*id].converted {
                    Val::plain(format!("(*{})", self.var_c[*id]))
                } else {
                    Val::plain(self.var_c[*id].clone())
                }
            }
            EK::Index(a, i) => {
                let av = self.expr(a);
                let av = if has_effects(i) { self.hold(av, &a.ty) } else { av };
                let iv = self.expr(i);
                match &a.ty {
                    Ty::Arr(el) => {
                        let cty = self.ct(el);
                        Val::plain(format!("(((({}*)({})->data))[gort_chk((size_t)({}), ({})->cap)])", cty, av.c, iv.c, av.c))
                    }
                    _ => Val::plain(format!("((uint8_t)({})->data[gort_chk((size_t)({}), ({})->cap)])", av.c, iv.c, av.c)),
                }
            }
            EK::Slice(a, lo, hi) => {
                let av = self.expr(a);
                let av = if lo.as_deref().map(has_effects).unwrap_or(false) || hi.as_deref().map(has_effects).unwrap_or(false) {
                    self.hold(av, &a.ty)
                } else {
                    av
                };
                let lov = match lo {
                    Some(x) => self.expr(x).c,
                    None => "0".to_string(),
                };
                let hiv = match hi {
                    Some(x) => self.expr(x).c,
                    None => format!("({})->len", av.c),
                };
                let el = match &a.ty {
                    Ty::Arr(el) => self.ct(el),
                    _ => unreachable!(),
                };
                let t = self.tmp();
                self.line(format!("gort_arr* {} = gort_arr_slice({}, sizeof({}), (size_t)({}), (size_t)({}));", t, av.c, el, lov, hiv));
                self.register_temp(&t, format!("gort_arr_release({});", t));
                Val { c: t.clone(), own: Some(t) }
            }
            EK::Len(a) => {
                let av = self.expr(a);
                Val::plain(format!("(({})->len)", av.c))
            }
            EK::Call(fid, args) => self.call(*fid, None, args, &e.ty),
            EK::Json(sid, bytes, lim) => {
                let sn = self.prog.structs[*sid].name.clone();
                JSONS.with(|j| j.borrow_mut().insert(*sid));
                let b = self.expr(bytes);
                let bn = self.tmp();
                self.line(format!("gort_arr* {} = {};", bn, b.c));
                let (md, ms) = match lim {
                    Some(l) => {
                        let lv = self.expr(l);
                        let ln = self.tmp();
                        let lty = self.ct(&l.ty);
                        self.line(format!("{} {} = {};", lty, ln, lv.c));
                        (format!("{}.f_maxDepth", ln), format!("{}.f_maxStringBytes", ln))
                    }
                    None => ("64".to_string(), "1048576".to_string()),
                };
                let (j, o) = (self.tmp(), self.tmp());
                self.line(format!("gort_jp {};", j));
                self.line(format!("gort_jp_init(&{}, {}, (long)({}), (long)({}));", j, bn, md, ms));
                self.line(format!("G_{} {}; memset(&{}, 0, sizeof {});", sn, o, o, o));
                let je = self.prog.structs.iter().position(|s| s.name == "JsonError").unwrap();
                self.line(format!("if (gort_jd_{}(&{}, &{}) || gort_jp_end(&{})) {{", sn, j, o, j));
                self.ind += 1;
                self.line(format!("G_JsonError* x = (G_JsonError*)gort_new(sizeof(G_JsonError));"));
                self.line(format!("x->f_message = gort_str_make((const uint8_t*){}.err, strlen({}.err));", j, j));
                self.line(format!(
                    "gort_exc.obj = x; gort_exc.id = {}; gort_exc.name = \"JsonError\"; gort_exc.rel = (void (*)(void*))G_JsonError_release;",
                    je + 1
                ));
                self.throw_exit();
                self.ind -= 1;
                self.line("}");
                match drop_code(self.prog, &Ty::Struct(*sid), &o) {
                    Some(d) => {
                        self.register_temp(&o, d);
                        Val { c: o.clone(), own: Some(o) }
                    }
                    None => Val::plain(o),
                }
            }
            EK::Zero => Val::plain(self.zero_c(&e.ty)),
            EK::CName(n) => Val::plain(n.clone()),
            EK::Borrow(inner) => {
                // a place behind a handle in shared storage: hold that handle (one count, released at statement end) so
                // the callee replacing the field cannot free what the lent address points into
                let pinned;
                let inner = if inner.place_stable() {
                    inner
                } else {
                    pinned = self.pin_owner(inner);
                    &pinned
                };
                let v = self.expr(inner);
                let lvalue = v.own.is_none() && !v.c.is_empty() && v.c.chars().all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '_' | '.' | '>' | '-' | '*' | '(' | ')' | '[' | ']'));
                if let (true, Some(n)) = (v.own.is_some(), v.own.clone()) {
                    Val::plain(format!("(&{})", n))
                } else if lvalue {
                    Val::plain(format!("(&{})", v.c))
                } else {
                    // not a place (a call result, an unwrapped optional): look at it through a temporary that lives to the end of the statement
                    let t = self.tmp();
                    let cty = self.ct(&inner.ty);
                    self.line(format!("{} {} = {};", cty, t, v.c));
                    Val::plain(format!("(&{})", t))
                }
            }
            EK::BoxVal(inner) => {
                let Ty::Ref(s) = &e.ty else { unreachable!() };
                let sn = self.prog.structs[*s].name.clone();
                let v = self.expr(inner);
                let o = self.own_value(v, &inner.ty);
                let t = self.tmp();
                self.line(format!("G_{0}* {1} = (G_{0}*)gort_new(sizeof(G_{0})); *{1} = {2};", sn, t, o));
                self.unregister(&o);
                self.register_temp(&t, format!("G_{}_release({});", sn, t));
                Val { c: t.clone(), own: Some(t) }
            }
            EK::Lambda(..) => unreachable!("a lambda with captures is only valid as an argument to a runtime function"),
            EK::ExternFn(inner) => {
                let Ty::Fn(ps, r, th) = &inner.ty else { unreachable!() };
                self.labels += 1;
                let n = self.labels;
                let pt: Vec<String> = ps.iter().map(|p| self.ct(p)).collect();
                let rt = if *th { "int".to_string() } else { self.ct(r) };
                let mut sig: Vec<String> = pt.iter().enumerate().map(|(i, t)| format!("{} a{}", t, i)).collect();
                let mut cargs: Vec<String> = (0..pt.len()).map(|i| format!("a{}", i)).collect();
                let mut ctys = pt.clone();
                if *th && **r != Ty::Unit {
                    sig.push(format!("{}* r", self.ct(r)));
                    cargs.push("r".into());
                    ctys.push(format!("{}*", self.ct(r)));
                }
                let sigs = std::iter::once("void* env".to_string()).chain(sig).collect::<Vec<_>>().join(", ");
                let ret_kw = if rt == "void" { "" } else { "return " };
                match &inner.kind {
                    EK::FnRef(..) => {
                        let f = self.expr(inner);
                        let def = format!(
                            "static {rt} gort_ext{n}({sigs}) {{ (void)env; {ret_kw}(({rt} (*)({ct}))({f}))({ca}); }}\n",
                            rt = rt, n = n, sigs = sigs, ret_kw = ret_kw, ct = if ctys.is_empty() { "void".into() } else { ctys.join(", ") }, f = f.c, ca = cargs.join(", ")
                        );
                        EXTDEFS.with(|e| e.borrow_mut().push(def));
                        Val::plain(format!("(void*)gort_ext{}, NULL", n))
                    }
                    EK::Lambda(fid, caps) => {
                        let cts: Vec<String> = caps.iter().map(|c| self.ct(&c.ty)).collect();
                        let fields: String = cts.iter().enumerate().map(|(i, t)| format!("{} c{}; ", t, i)).collect();
                        let cname = self.prog.fns[*fid].cname.clone();
                        let mut call_args: Vec<String> = (0..caps.len()).map(|i| format!("v.c{}", i)).collect();
                        call_args.extend(cargs.iter().cloned());
                        let def = format!(
                            "typedef struct {{ {fields}}} gort_env{n};\nstatic {rt} gort_ext{n}({sigs}) {{ gort_env{n} v = *(gort_env{n}*)env; free(env); {ret_kw}{cname}({ca}); }}\n",
                            fields = fields, n = n, rt = rt, sigs = sigs, ret_kw = ret_kw, cname = cname, ca = call_args.join(", ")
                        );
                        EXTDEFS.with(|e| e.borrow_mut().push(def));
                        let t = self.tmp();
                        self.line(format!("gort_env{0}* {1} = (gort_env{0}*)malloc(sizeof(gort_env{0}));", n, t));
                        for (i, cap) in caps.iter().enumerate() {
                            let v = self.expr(cap);
                            let o = self.own_value(v, &cap.ty);
                            self.line(format!("{}->c{} = {};", t, i, o));
                            self.unregister(&o);
                        }
                        Val::plain(format!("(void*)gort_ext{}, (void*){}", n, t))
                    }
                    _ => unreachable!(),
                }
            }
            EK::RtCall(name, args) => {
                if *name == "min" || *name == "max" {
                    let x = self.expr(&args[0]);
                    let xn = self.tmp();
                    let cty = self.ct(&args[0].ty);
                    self.line(format!("{} {} = {};", cty, xn, x.c));
                    let y = self.expr(&args[1]);
                    let yn = self.tmp();
                    self.line(format!("{} {} = {};", cty, yn, y.c));
                    return Val::plain(format!("(({0}) {1} ({2}) ? ({0}) : ({2}))", xn, if *name == "min" { "<" } else { ">" }, yn));
                }
                if matches!(*name, "find" | "contains" | "startsWith" | "copyFrom") {
                    let data = |g: &mut Self, e: &TExpr| -> (String, String) {
                        let v = g.expr(e);
                        let n = g.tmp();
                        if e.ty == Ty::Str {
                            g.line(format!("gort_str* {} = {};", n, v.c));
                        } else {
                            g.line(format!("gort_arr* {} = {};", n, v.c));
                        }
                        (format!("(const uint8_t*){}->data", n), format!("{}->len", n))
                    };
                    let (hd, hl) = data(self, &args[0]);
                    let (nd, nl) = data(self, &args[1]);
                    return match *name {
                        "copyFrom" => {
                            self.line(format!("if ({} != {}) gort_trap(\"copyFrom: lengths differ\");", hl, nl));
                            self.line(format!("memmove((void*){}, {}, {});", hd, nd, nl));
                            Val::plain("")
                        }
                        "startsWith" => Val::plain(format!("({0} >= {1} && memcmp({2}, {3}, {1}) == 0)", hl, nl, hd, nd)),
                        "contains" => Val::plain(format!("(gort_mem_find({}, {}, {}, {}) >= 0)", hd, hl, nd, nl)),
                        _ => {
                            let t = self.tmp();
                            let cty = self.ct(&Ty::Opt(Box::new(Ty::Int(IntTy::Usize))));
                            let r = self.tmp();
                            self.line(format!("long {} = gort_mem_find({}, {}, {}, {});", r, hd, hl, nd, nl));
                            self.line(format!("{} {} = {{ .has = {} >= 0, .v = (size_t){} }};", cty, t, r, r));
                            Val::plain(t)
                        }
                    };
                }
                let a = self.expr(&args[0]);
                if *name == "toBytes" {
                    let t = self.tmp();
                    self.line(format!("gort_arr* {} = gort_arr_new(1, {}->len); memcpy({}->data, {}->data, {}->len);", t, a.c, t, a.c, a.c));
                    self.register_temp(&t, format!("gort_arr_release({});", t));
                    return Val { c: t.clone(), own: Some(t) };
                }
                if *name == "capacity" {
                    return Val::plain(format!("(({})->cap)", a.c));
                }
                if *name == "appendArr" {
                    let b = self.expr(&args[1]);
                    self.line(format!("gort_arr_append({}, ({})->data, ({})->len);", a.c, b.c, b.c));
                    return Val::plain("");
                }
                if *name == "appendOne" {
                    let b = self.expr(&args[1]);
                    let t = self.tmp();
                    let cty = self.ct(&args[1].ty);
                    self.line(format!("{} {} = {};", cty, t, b.c));
                    self.line(format!("gort_arr_append({}, &{}, 1);", a.c, t));
                    return Val::plain("");
                }
                if *name == "grow" {
                    self.line(format!("gort_arr_grow({});", a.c));
                } else {
                    let ac = self.tmp();
                    self.line(format!("gort_arr* {} = {};", ac, a.c));
                    let r = self.expr(&args[1]);
                    let rt = self.tmp();
                    let rty = self.ct(&args[1].ty);
                    self.line(format!("{} {} = {};", rty, rt, r.c));
                    let to = self.expr(&args[2]);
                    self.line(format!("gort_arr_move({}, {}.f_lo, {}.f_hi, {});", ac, rt, rt, to.c));
                }
                Val::plain("")
            }
            EK::FnRef(fid, th) => {
                let f = &self.prog.fns[*fid];
                if *th && f.throws.is_empty() {
                    THUNKS.with(|t| t.borrow_mut().insert(*fid));
                    Val::plain(format!("(void*){}_thunk", f.cname))
                } else {
                    Val::plain(format!("(void*){}", f.cname))
                }
            }
            EK::CallInd(f, args) => {
                let Ty::Fn(ps, r, th) = &f.ty else { unreachable!() };
                let fv = self.expr(f);
                let mut sig: Vec<String> = ps.iter().map(|p| self.ct(p)).collect();
                if *th && **r != Ty::Unit {
                    sig.push(format!("{}*", self.ct(r)));
                }
                let rt = if *th { "int".to_string() } else { self.ct(r) };
                let target = format!("(({} (*)({})){})", rt, if sig.is_empty() { "void".into() } else { sig.join(", ") }, fv.c);
                self.call_c(target, *th, None, args, &e.ty, &[])
            }
            EK::Method(fid, recv, args) => {
                let rv = self.expr(recv);
                let rv = if args.iter().any(has_effects) { self.hold_place(rv) } else { rv };
                self.call(*fid, Some(rv), args, &e.ty)
            }
            EK::Builtin(b, args) => self.builtin(*b, args, &e.ty),
            EK::Unary(op, x) => {
                let xv = self.expr(x);
                match op {
                    UnOp::Neg => Val::plain(format!("(-({}))", xv.c)),
                    UnOp::Not => Val::plain(format!("(!({}))", xv.c)),
                }
            }
            EK::Binary(op, a, b) => self.binary(*op, a, b, &e.ty),
            EK::StructLit(sid, fields) => {
                let fs = self.eval_fields(fields);
                let sn = self.prog.structs[*sid].name.clone();
                let t = self.tmp();
                self.line(format!("G_{} {};", sn, t));
                if self.prog.structs[*sid].fields.is_empty() {
                    self.line(format!("{}._empty = 0;", t));
                }
                for (idx, o) in fs {
                    let fname = field_c(&self.prog.structs[*sid].fields[idx].name);
                    self.line(format!("{}.{} = {};", t, fname, o));
                    self.unregister(&o);
                }
                if self.prog.structs[*sid].needs_drop {
                    self.register_temp(&t, format!("G_{}_drop(&{});", sn, t));
                    Val { c: t.clone(), own: Some(t) }
                } else {
                    Val::plain(t)
                }
            }
            EK::NewObj(sid, fields) => {
                let fs = self.eval_fields(fields);
                let sn = self.prog.structs[*sid].name.clone();
                let t = self.tmp();
                self.line(format!("G_{0}* {1} = (G_{0}*)gort_new(sizeof(G_{0}));", sn, t));
                for (idx, o) in fs {
                    let fname = field_c(&self.prog.structs[*sid].fields[idx].name);
                    self.line(format!("{}->{} = {};", t, fname, o));
                    self.unregister(&o);
                }
                self.register_temp(&t, format!("G_{}_release({});", sn, t));
                Val { c: t.clone(), own: Some(t) }
            }
            EK::NewArr(el, len) => {
                let lv = self.expr(len);
                let cty = self.ct(el);
                let t = self.tmp();
                match drop_code(self.prog, el, "(*e)") {
                    Some(_) => {
                        let name: String = format!("gort_edrop_{}", self.prog.type_name(el).chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect::<String>());
                        EDROPS.with(|m| m.borrow_mut().insert(name.clone(), el.clone()));
                        self.line(format!("gort_arr* {} = gort_arr_new_d(sizeof({}), (size_t)({}), {});", t, cty, lv.c, name));
                    }
                    None => self.line(format!("gort_arr* {} = gort_arr_new(sizeof({}), (size_t)({}));", t, cty, lv.c)),
                }
                self.register_temp(&t, format!("gort_arr_release({});", t));
                Val { c: t.clone(), own: Some(t) }
            }
            EK::Null => {
                if e.ty.is_handle_opt() {
                    Val::plain("NULL")
                } else {
                    let cty = self.ct(&e.ty);
                    Val::plain(format!("(({}){{ false }})", cty))
                }
            }
            EK::Some(x) => {
                let xv = self.expr(x);
                if x.ty.is_handle() {
                    xv
                } else {
                    let cty = self.ct(&e.ty);
                    Val::plain(format!("(({}){{ true, {} }})", cty, xv.c))
                }
            }
            EK::IsNull(x) => {
                let xv = self.expr(x);
                if e.ty == Ty::Bool && matches!(&x.ty, Ty::Opt(i) if i.is_handle()) {
                    Val::plain(format!("(({}) == NULL)", xv.c))
                } else {
                    Val::plain(format!("(!({}).has)", xv.c))
                }
            }
            EK::Unwrap(x) => {
                let xv = self.expr(x);
                let h = self.hold(Val { c: xv.c, own: None }, &x.ty);
                let null_exc = self.prog.null_exc;
                let handled = self.try_stack.iter().any(|t| t.catches_null)
                    || self.f.throws.iter().any(|t| *t == ANY_EXC || Some(*t) == null_exc);
                let handle = e.ty.is_handle();
                if handled {
                    // a null value is a NullValue exception, taken by the nearest `try` that catches it or by the caller
                    self.line(if handle { format!("if (!{}) {{", h.c) } else { format!("if (!{}.has) {{", h.c) });
                    self.ind += 1;
                    let sid = null_exc.unwrap();
                    let sn = self.prog.structs[sid].name.clone();
                    let t = self.tmp();
                    self.line(format!("G_{0}* {1} = (G_{0}*)gort_new(sizeof(G_{0}));", sn, t));
                    self.line(format!(
                        "gort_exc.obj = {}; gort_exc.id = {}; gort_exc.name = \"{}\"; gort_exc.rel = (void (*)(void*))G_{}_release;",
                        t,
                        sid + 1,
                        sn,
                        sn
                    ));
                    self.throw_exit();
                    self.ind -= 1;
                    self.line("}");
                    if handle {
                        let cty = self.ct(&e.ty);
                        Val::plain(format!("(({}){})", cty, h.c))
                    } else {
                        Val::plain(format!("{}.v", h.c))
                    }
                } else if handle {
                    let cty = self.ct(&e.ty);
                    Val::plain(format!("(({})gort_nn({}))", cty, h.c))
                } else {
                    Val::plain(format!("(gort_has({0}.has), {0}.v)", h.c))
                }
            }
            EK::ArrLit(el, items) => {
                let cty = self.ct(el);
                let t = self.tmp();
                match drop_code(self.prog, el, "(*e)") {
                    Some(_) => {
                        let name: String = format!("gort_edrop_{}", self.prog.type_name(el).chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect::<String>());
                        EDROPS.with(|m| m.borrow_mut().insert(name.clone(), el.clone()));
                        self.line(format!("gort_arr* {} = gort_arr_new_d(sizeof({}), {}, {});", t, cty, items.len(), name));
                    }
                    None => self.line(format!("gort_arr* {} = gort_arr_new(sizeof({}), {});", t, cty, items.len())),
                }
                self.register_temp(&t, format!("gort_arr_release({});", t));
                for (i, it) in items.iter().enumerate() {
                    let v = self.expr(it);
                    let o = self.own_value(v, &it.ty);
                    self.line(format!("(({}*){}->data)[{}] = {};", cty, t, i, o));
                    self.unregister(&o);
                }
                Val { c: t.clone(), own: Some(t) }
            }
            EK::Cond(c, a, b) => {
                let cv = self.expr(c);
                let cn = self.tmp();
                self.line(format!("bool {} = {};", cn, cv.c));
                let t = self.tmp();
                let cty = self.ct(&e.ty);
                self.line(format!("{} {};", cty, t));
                for (i, branch) in [a, b].into_iter().enumerate() {
                    self.line(if i == 0 { format!("if ({}) {{", cn) } else { "} else {".to_string() });
                    self.ind += 1;
                    self.push_frame();
                    let v = self.expr(branch);
                    let o = self.own_value(v, &branch.ty);
                    self.line(format!("{} = {};", t, o));
                    self.pop_frame();
                    self.ind -= 1;
                }
                self.line("}");
                match drop_code(self.prog, &e.ty, &t) {
                    Some(d) => {
                        self.register_temp(&t, d);
                        Val { c: t.clone(), own: Some(t) }
                    }
                    None => Val::plain(t),
                }
            }
            EK::Cast(x) => {
                let xv = self.expr(x);
                let cty = self.ct(&e.ty);
                Val::plain(format!("(({})({}))", cty, xv.c))
            }
        }
    }

    /// Rewrites a place so the unstable handle on its path (a field, element or global holding the owner) is read once into a
    /// counted temporary that lives to the end of the statement; the place is then reached through that temporary.
    fn pin_owner(&mut self, e: &TExpr) -> TExpr {
        let pin = |g: &mut Self, h: &TExpr| -> TExpr {
            let v = g.expr(h);
            let c = g.copy_value(v, &h.ty);
            if let Some(d) = drop_code(g.prog, &h.ty, &c) {
                g.register_temp(&c, d);
            }
            TExpr { kind: EK::CName(c), ..h.clone() }
        };
        let kind = match &e.kind {
            EK::Field(b, f) => EK::Field(Box::new(self.pin_owner(b)), f.clone()),
            EK::Deref(h) if !h.handle_stable() => EK::Deref(Box::new(pin(self, h))),
            EK::Index(a, i) if !a.handle_stable() => EK::Index(Box::new(pin(self, a)), i.clone()),
            _ => return e.clone(),
        };
        TExpr { kind, ..e.clone() }
    }

    /// Freeze a value into a temporary so a later operand with side effects cannot change it.
    fn hold(&mut self, v: Val, ty: &Ty) -> Val {
        if v.own.is_some() || ty_is_temp_name(&v.c) {
            return v;
        }
        let t = self.tmp();
        let cty = self.ct(ty);
        self.line(format!("{} {} = {};", cty, t, v.c));
        Val::plain(t)
    }
    fn hold_place(&mut self, v: Val) -> Val {
        // a place is addressed, not copied; its C text names variables and temporaries only, so it stays valid
        v
    }

    fn call(&mut self, fid: FnId, recv: Option<Val>, args: &[TExpr], ret: &Ty) -> Val {
        let throws = !self.prog.fns[fid].throws.is_empty();
        let cname = self.prog.fns[fid].cname.clone();
        let borrowed = self.prog.fns[fid].borrowed.clone();
        self.call_c(cname, throws, recv, args, ret, &borrowed)
    }

    fn call_c(&mut self, cname: String, throws: bool, recv: Option<Val>, args: &[TExpr], ret: &Ty, borrowed: &[bool]) -> Val {
        let mut cargs: Vec<String> = Vec::new();
        if let Some(r) = recv {
            cargs.push(format!("&({})", r.c));
        }
        let mut copies: Vec<String> = Vec::new();
        for (i, a) in args.iter().enumerate() {
            let v = self.expr(a);
            // a borrowing parameter takes the pointer as it is: no count moves, and the caller's variable keeps it alive
            let lends = borrowed.get(i).copied().unwrap_or(false);
            if matches!(a.kind, EK::ExternFn(_) | EK::Borrow(_)) || (lends && a.handle_stable()) {
                cargs.push(v.c);
                continue;
            }
            let c = self.copy_value(v, &a.ty);
            // an argument copy is owned by the callee, but until the call a later argument that throws must release it.
            // A handle read from shared storage and given to a borrowing parameter is kept alive by the caller until the
            // statement ends, in case the callee replaces the field it came from.
            if let Some(d) = drop_code(self.prog, &a.ty, &c) {
                self.register_temp(&c, d);
                if !lends {
                    copies.push(c.clone());
                }
            }
            cargs.push(c);
        }
        let t = self.tmp();
        let cty = self.ct(ret);
        if throws && *ret != Ty::Unit {
            self.line(format!("{} {};", cty, t));
            cargs.push(format!("&{}", t));
        }
        let call = format!("{}({})", cname, cargs.join(", "));
        // the callee owns the copies from here on, also when it throws
        for c in &copies {
            self.unregister(c);
        }
        if throws {
            self.line(format!("if ({}) {{", call));
            self.ind += 1;
            self.throw_exit();
            self.ind -= 1;
            self.line("}");
            if *ret == Ty::Unit {
                return Val::plain("");
            }
        } else if *ret == Ty::Unit {
            self.line(format!("{};", call));
            return Val::plain("");
        } else {
            self.line(format!("{} {} = {};", cty, t, call));
        }
        match drop_code(self.prog, ret, &t) {
            Some(d) => {
                self.register_temp(&t, d);
                Val { c: t.clone(), own: Some(t) }
            }
            None => Val::plain(t),
        }
    }

    fn builtin(&mut self, b: Builtin, args: &[TExpr], ret: &Ty) -> Val {
        if b == Builtin::Now {
            let t = self.tmp();
            self.line(format!("int64_t {} = gort_now_ns();", t));
            return Val::plain(t);
        }
        let a = &args[0];
        let v = self.expr(a);
        match b {
            Builtin::Now => unreachable!(),
            Builtin::Assert => {
                self.line(format!("if (!({})) gort_trap(\"assertion failed (line {})\");", v.c, a.line));
                Val::plain("")
            }
            Builtin::Print | Builtin::Println => {
                let call = match &a.ty {
                    Ty::Str => format!("gort_print_str({});", v.c),
                    Ty::Bool => format!("gort_print_b({});", v.c),
                    Ty::F64 => format!("gort_print_f({});", v.c),
                    Ty::Int(it) if matches!(it, IntTy::U8 | IntTy::U16 | IntTy::U32 | IntTy::U64 | IntTy::Usize) => {
                        format!("gort_print_u((unsigned long long)({}));", v.c)
                    }
                    _ => format!("gort_print_i((long long)({}));", v.c),
                };
                self.line(call);
                if b == Builtin::Println {
                    self.line("gort_nl();");
                }
                Val::plain("")
            }
            Builtin::Hash => {
                let t = self.tmp();
                let e = match &a.ty {
                    Ty::Str => format!("gort_hash_str({})", v.c),
                    _ => format!("gort_hash_u((uint64_t)({}))", v.c),
                };
                self.line(format!("uint64_t {} = {};", t, e));
                Val::plain(t)
            }
            Builtin::Str => {
                let f = match &a.ty {
                    Ty::Bool => format!("gort_str_from_b({})", v.c),
                    Ty::F64 => format!("gort_str_from_f({})", v.c),
                    Ty::Int(it) if matches!(it, IntTy::U8 | IntTy::U16 | IntTy::U32 | IntTy::U64 | IntTy::Usize) => {
                        format!("gort_str_from_u((unsigned long long)({}))", v.c)
                    }
                    _ => format!("gort_str_from_i((long long)({}))", v.c),
                };
                let _ = ret;
                let t = self.tmp();
                self.line(format!("gort_str* {} = {};", t, f));
                self.register_temp(&t, format!("gort_str_release({});", t));
                Val { c: t.clone(), own: Some(t) }
            }
        }
    }

    fn binary(&mut self, op: BinOp, a: &TExpr, b: &TExpr, ty: &Ty) -> Val {
        if matches!(op, BinOp::And | BinOp::Or) {
            let av = self.expr(a);
            let t = self.tmp();
            self.line(format!("bool {} = {};", t, av.c));
            self.line(if op == BinOp::And { format!("if ({}) {{", t) } else { format!("if (!{}) {{", t) });
            self.ind += 1;
            self.push_frame();
            let bv = self.expr(b);
            self.line(format!("{} = {};", t, bv.c));
            self.pop_frame();
            self.ind -= 1;
            self.line("}");
            return Val::plain(t);
        }
        let av = self.expr(a);
        let av = if has_effects(b) { self.hold(av, &a.ty) } else { av };
        let bv = self.expr(b);
        match (&a.ty, op) {
            (Ty::Str, BinOp::Add) => {
                let t = self.tmp();
                self.line(format!("gort_str* {} = gort_str_concat({}, {});", t, av.c, bv.c));
                self.register_temp(&t, format!("gort_str_release({});", t));
                Val { c: t.clone(), own: Some(t) }
            }
            (Ty::Struct(s), BinOp::Eq | BinOp::Ne) => {
                EQS.with(|q| q.borrow_mut().insert(*s));
                let (x, y) = (self.tmp(), self.tmp());
                let cn = self.prog.structs[*s].name.clone();
                self.line(format!("G_{0} {1} = {2}; G_{0} {3} = {4};", cn, x, av.c, y, bv.c));
                let call = format!("gort_eq_{}(&{}, &{})", cn, x, y);
                Val::plain(if op == BinOp::Eq { call } else { format!("(!{})", call) })
            }
            (Ty::Str, BinOp::Eq) => Val::plain(format!("gort_str_eq({}, {})", av.c, bv.c)),
            (Ty::Str, BinOp::Ne) => Val::plain(format!("(!gort_str_eq({}, {}))", av.c, bv.c)),
            (Ty::Int(_), BinOp::Div) | (Ty::Int(_), BinOp::Rem) => {
                let _ = ty;
                Val::plain(format!("(GORT_NZ({}), (({}) {} ({})))", bv.c, av.c, binop_c(op), bv.c))
            }
            _ => Val::plain(format!("(({}) {} ({}))", av.c, binop_c(op), bv.c)),
        }
    }
}

fn opt_name(prog: &Program, inner: &Ty) -> String {
    let m = match inner {
        Ty::Int(i) => i.name().to_string(),
        Ty::Bool => "bool".into(),
        Ty::F64 => "f64".into(),
        Ty::Struct(s) => format!("S_{}", prog.structs[*s].name),
        _ => "x".into(),
    };
    format!("gort_opt_{}", m)
}

fn ty_is_temp_name(c: &str) -> bool {
    c.starts_with('t') && c.len() > 1 && c[1..].chars().all(|x| x.is_ascii_digit())
}

fn binop_c(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "+",
        BinOp::Sub => "-",
        BinOp::Mul => "*",
        BinOp::Div => "/",
        BinOp::Rem => "%",
        BinOp::Eq => "==",
        BinOp::Ne => "!=",
        BinOp::Lt => "<",
        BinOp::Le => "<=",
        BinOp::Gt => ">",
        BinOp::Ge => ">=",
        BinOp::And => "&&",
        BinOp::Or => "||",
    }
}

/// One decoder per struct that `json.parse` reaches (nested structs included).
fn json_decoders(prog: &Program) -> String {
    let mut want: std::collections::BTreeSet<usize> = JSONS.with(|j| std::mem::take(&mut *j.borrow_mut()));
    let mut todo: Vec<usize> = want.iter().copied().collect();
    while let Some(s) = todo.pop() {
        for f in &prog.structs[s].fields {
            let mut t = &f.ty;
            if let Ty::Opt(i) = t {
                t = i;
            }
            if let Ty::Struct(n) = t {
                if want.insert(*n) {
                    todo.push(*n);
                }
            }
        }
    }
    let mut out = String::new();
    for s in &want {
        out.push_str(&format!("static int gort_jd_{0}(gort_jp *j, G_{0} *o);\n", prog.structs[*s].name));
    }
    for s in &want {
        let si = &prog.structs[*s];
        let n = &si.name;
        out.push_str(&format!("static int gort_jd_{0}(gort_jp *j, G_{0} *o) {{\n    uint64_t seen = 0;\n", n));
        out.push_str("    if (gort_jp_expect(j, '{')) return 1;\n");
        out.push_str("    if (++j->depth > j->maxdepth) return gort_jp_fail(j, \"nesting too deep\");\n");
        out.push_str("    if (gort_jp_peek(j) == '}') { j->p++; } else for (;;) {\n");
        out.push_str("        const uint8_t *k; size_t kn;\n        if (gort_jp_key(j, &k, &kn) || gort_jp_expect(j, ':')) goto fail;\n        ");
        for (i, f) in si.fields.iter().enumerate() {
            let lv = format!("o->{}", field_c(&f.name));
            out.push_str(&format!(
                "if (kn == {} && !memcmp(k, \"{}\", {})) {{\n            if (seen & (1ULL << {})) {{ gort_jp_fail(j, \"duplicate field {}\"); goto fail; }}\n            if ({}) goto fail;\n            seen |= 1ULL << {};\n        }} else ",
                f.name.len(), f.name, f.name.len(), i, f.name, json_field(prog, &f.ty, &lv), i
            ));
        }
        out.push_str("{ if (gort_jp_skip(j)) goto fail; }\n");
        out.push_str("        { int c = gort_jp_peek(j); if (c == ',') { j->p++; continue; } if (c == '}') { j->p++; break; } gort_jp_fail(j, \"expected ',' or '}'\"); goto fail; }\n    }\n");
        out.push_str("    j->depth--;\n");
        for (i, f) in si.fields.iter().enumerate() {
            if !matches!(f.ty, Ty::Opt(_)) {
                out.push_str(&format!("    if (!(seen & (1ULL << {}))) {{ gort_jp_fail(j, \"missing field {}\"); goto fail; }}\n", i, f.name));
            }
        }
        out.push_str("    return 0;\nfail:\n");
        for (i, f) in si.fields.iter().enumerate() {
            if let Some(d) = drop_code(prog, &f.ty, &format!("o->{}", field_c(&f.name))) {
                out.push_str(&format!("    if (seen & (1ULL << {})) {{ {} }}\n", i, d));
            }
        }
        out.push_str("    return 1;\n}\n");
    }
    out
}

/// An expression that decodes one value into the lvalue `lv`; nonzero when it fails.
fn json_field(prog: &Program, t: &Ty, lv: &str) -> String {
    match t {
        Ty::Int(i) => {
            let (signed, lo, hi) = match i.name() {
                "i8" => (true, "INT8_MIN", "INT8_MAX"),
                "i16" => (true, "INT16_MIN", "INT16_MAX"),
                "i32" => (true, "INT32_MIN", "INT32_MAX"),
                "i64" | "isize" => (true, "INT64_MIN", "INT64_MAX"),
                "u8" => (false, "0", "UINT8_MAX"),
                "u16" => (false, "0", "UINT16_MAX"),
                "u32" => (false, "0", "UINT32_MAX"),
                _ => (false, "0", "UINT64_MAX"),
            };
            let ct = i.c_name();
            if signed {
                format!("({{ int64_t v_ = 0; int r_ = gort_jp_int(j, &v_, {}, {}); if (!r_) {} = ({})v_; r_; }})", lo, hi, lv, ct)
            } else {
                format!("({{ uint64_t v_ = 0; int r_ = gort_jp_uint(j, &v_, {}); if (!r_) {} = ({})v_; r_; }})", hi, lv, ct)
            }
        }
        Ty::Bool => format!("gort_jp_bool(j, &{})", lv),
        Ty::F64 => format!("gort_jp_f64(j, &{})", lv),
        Ty::Str => format!("gort_jp_str(j, &{})", lv),
        Ty::Struct(s) => format!("gort_jd_{}(j, &{})", prog.structs[*s].name, lv),
        Ty::Opt(inner) if inner.is_handle() => format!("(gort_jp_isnull(j) ? 0 : {})", json_field(prog, inner, lv)),
        Ty::Opt(inner) => {
            let v = format!("{}.v", lv);
            format!("(gort_jp_isnull(j) ? 0 : ({{ int r_ = {}; if (!r_) {}.has = true; r_; }}))", json_field(prog, inner, &v), lv)
        }
        _ => "1".into(),
    }
}

/// `gort_eq_S(a, b)` for every struct or enum that `==` reaches (nested ones included).
fn eq_defs(prog: &Program) -> String {
    let mut want: std::collections::BTreeSet<usize> = EQS.with(|q| std::mem::take(&mut *q.borrow_mut()));
    let mut todo: Vec<usize> = want.iter().copied().collect();
    while let Some(s) = todo.pop() {
        for f in &prog.structs[s].fields {
            let t = if let Ty::Opt(i) = &f.ty { &**i } else { &f.ty };
            if let Ty::Struct(n) = t {
                if want.insert(*n) {
                    todo.push(*n);
                }
            }
        }
    }
    let eq = |t: &Ty, a: &str, b: &str| -> String {
        let one = |t: &Ty, a: &str, b: &str| -> String {
            match t {
                Ty::Str => format!("gort_str_eq({}, {})", a, b),
                Ty::Struct(n) => format!("gort_eq_{}(&{}, &{})", prog.structs[*n].name, a, b),
                _ => format!("{} == {}", a, b),
            }
        };
        match t {
            Ty::Opt(i) if i.is_handle() => match &**i {
                Ty::Str => format!("({0} == {1} || ({0} && {1} && gort_str_eq({0}, {1})))", a, b),
                _ => format!("{} == {}", a, b),
            },
            Ty::Opt(i) => format!("({0}.has == {1}.has && (!{0}.has || {2}))", a, b, one(i, &format!("{}.v", a), &format!("{}.v", b))),
            _ => one(t, a, b),
        }
    };
    let mut out = String::new();
    for s in &want {
        out.push_str(&format!("static bool gort_eq_{0}(const G_{0} *a, const G_{0} *b);\n", prog.structs[*s].name));
    }
    for s in &want {
        let si = &prog.structs[*s];
        out.push_str(&format!("static bool gort_eq_{0}(const G_{0} *a, const G_{0} *b) {{\n", si.name));
        if si.variants.is_empty() {
            let parts: Vec<String> = si.fields.iter().map(|f| eq(&f.ty, &format!("a->{}", field_c(&f.name)), &format!("b->{}", field_c(&f.name)))).collect();
            out.push_str(&format!("    return {};\n}}\n", if parts.is_empty() { "true".into() } else { parts.join(" && ") }));
        } else {
            out.push_str("    if (a->f__tag != b->f__tag) return false;\n    switch (a->f__tag) {\n");
            for (vi, v) in si.variants.iter().enumerate() {
                let parts: Vec<String> = v.fields.iter().map(|&i| {
                    let f = &si.fields[i];
                    eq(&f.ty, &format!("a->{}", field_c(&f.name)), &format!("b->{}", field_c(&f.name)))
                }).collect();
                if !parts.is_empty() {
                    out.push_str(&format!("    case {}: return {};\n", vi, parts.join(" && ")));
                }
            }
            out.push_str("    default: return true;\n    }\n}\n");
        }
    }
    out
}
